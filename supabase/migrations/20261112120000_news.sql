-- News shown on the public homepage of an Ortsgruppe (e.g. svoe.og125.at), maintained in this app.
-- Published news are readable without login (role anon) so the static homepage can fetch them;
-- writing is limited to users of the same organization, like the other tenant tables.
begin;

create table if not exists public.news (
    id integer generated by default as identity primary key,
    og integer not null,
    date date not null default current_date,
    title text not null,
    content text not null default '',
    "isPublished" boolean not null default true,
    "createdAt" timestamptz not null default now()
);

create index if not exists news_og_date_idx on public.news (og, date desc, id desc);

alter table public.news enable row level security;

drop policy if exists news_public_read on public.news;
create policy news_public_read on public.news
    for select to anon, authenticated
    using ("isPublished");

drop policy if exists news_tenant_all on public.news;
create policy news_tenant_all on public.news
    for all to authenticated
    using (exists (
        select 1 from public.users u where u.login = auth.jwt() ->> 'email' and u.og = news.og
    ))
    with check (exists (
        select 1 from public.users u where u.login = auth.jwt() ->> 'email' and u.og = news.og
    ));

grant select on public.news to anon;
grant select, insert, update, delete on public.news to authenticated;

commit;
