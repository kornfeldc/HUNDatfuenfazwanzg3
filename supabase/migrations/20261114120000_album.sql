-- Photo albums for the gallery on the public homepage of an Ortsgruppe (e.g. svoe.og125.at/fotos),
-- maintained in this app. The photos stay in Google Photos; a row holds the album's share link and cover image.
-- Published albums are readable without login (role anon) so the static homepage can fetch them;
-- writing is limited to users of the same organization, like the other tenant tables.
begin;

create table if not exists public.album (
    id integer generated by default as identity primary key,
    og integer not null,
    date date not null,
    "dateText" text,
    title text not null,
    link text not null,
    "coverUrl" text not null default '',
    "isPublished" boolean not null default true,
    "createdAt" timestamptz not null default now()
);

comment on column public.album.date is 'Sorts the gallery and sets its year filter.';
comment on column public.album."dateText" is 'Shown instead of the date when set, e.g. "2025" or "27.–28. Oktober 2018".';

create index if not exists album_og_date_idx on public.album (og, date desc, id desc);

alter table public.album enable row level security;

drop policy if exists album_public_read on public.album;
create policy album_public_read on public.album
    for select to anon, authenticated
    using ("isPublished");

drop policy if exists album_tenant_all on public.album;
create policy album_tenant_all on public.album
    for all to authenticated
    using (exists (
        select 1 from public.users u where u.login = auth.jwt() ->> 'email' and u.og = album.og
    ))
    with check (exists (
        select 1 from public.users u where u.login = auth.jwt() ->> 'email' and u.og = album.og
    ));

grant select on public.album to anon;
grant select, insert, update, delete on public.album to authenticated;

commit;
